import { XmlToken } from '../types/lexer.js';
import { XmlOptions, JsonNode } from '../types/index.js';

/**
 * Analyseur XML haute performance.
 * Consomme les jetons du Lexer et construit dynamiquement un AST léger de type JSON.
 * Préserve l'état entre les morceaux pour permettre le streaming asynchrone.
 */
export class Parser
{
    private options: XmlOptions;

    // La racine de notre objet JSON final.
    private racine: JsonNode = {};

    // Pointeur vers le nœud (objet) actuellement en cours de construction.
    private noeudCourant: JsonNode = this.racine;

    // Pile (Stack) permettant de remonter à l'objet parent quand on rencontre une balise fermante.
    private pile: { noeud: JsonNode; nomBalise: string }[] = [];

    /**
     * Initializes the parser with specific formatting and parsing options.
     * @param options - Configuration options for parsing.
     */
    constructor(options: XmlOptions = {})
    {
        this.options = options;
    }

    /**
     * Feeds an array of XML tokens into the parser to construct the AST.
     * Can be called multiple times sequentially with chunks of tokens.
     * 
     * @param tokens - The array of tokens generated by the Lexer.
     */
    public consume(tokens: XmlToken[]): void
    {
        for (const jeton of tokens)
        {
            switch (jeton.type)
            {

                case 'OpenTag':
                    const nomBalise = jeton.name!;
                    const nouvelEnfant: JsonNode = {};

                    // Ajout des attributs au nouvel enfant si ce n'est pas désactivé.
                    if (!this.options.ignoreAttributes && jeton.attributes)
                    {
                        Object.assign(nouvelEnfant, jeton.attributes);
                    }

                    // Gestion des balises multiples ayant le même nom (création d'un tableau).
                    if (this.noeudCourant[nomBalise] !== undefined)
                    {
                        // Si ce n'est pas encore un tableau, on le transforme en tableau.
                        if (!Array.isArray(this.noeudCourant[nomBalise]))
                        {
                            this.noeudCourant[nomBalise] = [this.noeudCourant[nomBalise]];
                        }
                        this.noeudCourant[nomBalise].push(nouvelEnfant);
                    } 
                    else
                    {
                        // C'est la première fois qu'on rencontre cette balise dans ce parent.
                        this.noeudCourant[nomBalise] = nouvelEnfant;
                    }

                    // Si la balise n'est pas auto-fermante (ex: pas de <Tag/>), on descend d'un niveau.
                    if (!jeton.isSelfClosing)
                    {
                        this.pile.push({ noeud: this.noeudCourant, nomBalise: nomBalise });
                        this.noeudCourant = nouvelEnfant;
                    }
                    break;

                case 'Text':
                    // On stocke temporairement le texte pur sous la clé interne '__text__'.
                    this.noeudCourant['__text__'] = jeton.value;
                    break;

                case 'CloseTag':
                    const parentInfos = this.pile.pop();
                    if (!parentInfos) break; // Sécurité si le XML est malformé

                    const cles = Object.keys(this.noeudCourant);
                    const nomFermeture = jeton.name!;

                    // COMPRESSION AST : Si le nœud courant ne contient QUE du texte (pas d'attributs, pas d'enfants),
                    // on évite de créer un objet complexe et on le remplace directement par sa valeur primitive.
                    // Exemple : { Age: { __text__: "30" } } -> { Age: "30" }
                    if (cles.length === 1 && cles[0] === '__text__')
                    {
                        const valeurTextePure = this.noeudCourant['__text__'];

                        if (Array.isArray(parentInfos.noeud[nomFermeture]))
                        {
                            // Si c'est un tableau, on remplace le dernier élément ajouté.
                            const tableau = parentInfos.noeud[nomFermeture];
                            tableau[tableau.length - 1] = valeurTextePure;
                        } 
                        else
                        {
                            // Sinon, on remplace simplement l'objet par la chaîne.
                            parentInfos.noeud[nomFermeture] = valeurTextePure;
                        }
                    }

                    // On remonte le pointeur vers le parent pour la suite de la lecture.
                    this.noeudCourant = parentInfos.noeud;
                    break;
            }
        }
    }

    public getAst(): JsonNode
    {
        return this.racine;
    }
}